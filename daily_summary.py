#!/usr/bin/env python3
"""
Daily Chief of Staff Summary
Fetches Granola meetings for the current day and sends a summary to Slack.
Triggered by Cursor Cloud Agent cron automation (runs daily at midnight UTC).

Required environment variables:
  SLACK_BOT_TOKEN - Slack Bot OAuth token (add as Cursor Cloud Agent secret)

The Granola data is fetched via the MCP tool output passed as stdin,
or via the GRANOLA_SUMMARY env var if pre-generated by the agent.
"""

import os
import sys
import json
from datetime import datetime, timezone, timedelta
from slack_sdk import WebClient
from slack_sdk.errors import SlackApiError


SLACK_CHANNEL_ID = "D06E4QMHCNN"
SLACK_BOT_TOKEN = os.environ.get("SLACK_BOT_TOKEN", "")


def send_slack_message(token: str, channel: str, blocks: list, text: str) -> bool:
    client = WebClient(token=token)
    try:
        response = client.chat_postMessage(
            channel=channel,
            blocks=blocks,
            text=text,
            unfurl_links=False,
            unfurl_media=False,
        )
        return response["ok"]
    except SlackApiError as e:
        print(f"Slack API Error: {e.response['error']}", file=sys.stderr)
        return False


def build_slack_blocks(summary_data: dict) -> tuple[list, str]:
    """Build Slack Block Kit message from summary data."""
    date_str = summary_data.get("date", "today")
    meetings = summary_data.get("meetings", [])
    decisions = summary_data.get("decisions", [])
    action_items = summary_data.get("action_items", [])
    themes = summary_data.get("themes", [])

    fallback_text = f"Daily PM Briefing — {date_str}"

    blocks = [
        {
            "type": "header",
            "text": {
                "type": "plain_text",
                "text": f"Your Daily Briefing — {date_str}",
                "emoji": True,
            },
        },
        {
            "type": "section",
            "text": {
                "type": "mrkdwn",
                "text": summary_data.get("opening", "Here's your end-of-day summary!"),
            },
        },
        {"type": "divider"},
    ]

    if meetings:
        blocks.append({
            "type": "section",
            "text": {
                "type": "mrkdwn",
                "text": f"*Meetings Today ({len(meetings)})*\n" + "\n".join(
                    f"• {m}" for m in meetings
                ),
            },
        })
        blocks.append({"type": "divider"})

    if decisions:
        decisions_text = "*Key Decisions Made Today*\n" + "\n".join(
            f"{i+1}. {d}" for i, d in enumerate(decisions)
        )
        blocks.append({
            "type": "section",
            "text": {"type": "mrkdwn", "text": decisions_text},
        })
        blocks.append({"type": "divider"})

    if action_items:
        actions_text = "*Your Action Items*\n" + "\n".join(
            f"• {a}" for a in action_items
        )
        blocks.append({
            "type": "section",
            "text": {"type": "mrkdwn", "text": actions_text},
        })
        blocks.append({"type": "divider"})

    if themes:
        themes_text = "*Cross-Cutting Themes*\n" + "\n".join(
            f"• {t}" for t in themes
        )
        blocks.append({
            "type": "section",
            "text": {"type": "mrkdwn", "text": themes_text},
        })
        blocks.append({"type": "divider"})

    blocks.append({
        "type": "section",
        "text": {
            "type": "mrkdwn",
            "text": summary_data.get(
                "closing",
                "_You crushed it today, Manan. Have a great evening!_",
            ),
        },
    })

    return blocks, fallback_text


def main():
    if len(sys.argv) > 1:
        with open(sys.argv[1]) as f:
            summary_data = json.load(f)
    elif not sys.stdin.isatty():
        summary_data = json.load(sys.stdin)
    else:
        print("Usage: python3 daily_summary.py <summary.json>", file=sys.stderr)
        print("Or pipe JSON summary data via stdin.", file=sys.stderr)
        sys.exit(1)

    blocks, fallback_text = build_slack_blocks(summary_data)

    if not SLACK_BOT_TOKEN:
        print("ERROR: SLACK_BOT_TOKEN environment variable not set.", file=sys.stderr)
        print("Add your Slack Bot Token as a Cursor Cloud Agent secret.", file=sys.stderr)
        print("\n--- Message that would be sent ---")
        print(json.dumps({"blocks": blocks, "text": fallback_text}, indent=2))
        sys.exit(1)

    success = send_slack_message(SLACK_BOT_TOKEN, SLACK_CHANNEL_ID, blocks, fallback_text)
    if success:
        print(f"Successfully sent daily summary to Slack channel {SLACK_CHANNEL_ID}")
    else:
        print("Failed to send Slack message.", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
